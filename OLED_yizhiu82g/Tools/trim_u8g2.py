# -*- coding: utf-8 -*-
"""Trim the u8g2 C sources for STM32F103C8T6 + SSD1306 128x64 I2C.

Only the files needed by a full-buffer SSD1306 I2C application are copied,
u8g2_d_setup.c is rebuilt with the three noname setups and u8g2_fonts.c is
rebuilt with five small ASCII fonts.  This keeps flash usage inside 64 KB.
"""
import os
import re
import shutil

SRC = r"D:\Keil5\STM32projecthal\00_u8g2-master\u8g2-master"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DST = os.path.join(ROOT, "Middlewares", "Third_Party", "u8g2")
CSRC = os.path.join(DST, "csrc")

COPY = [
    "u8g2.h", "u8x8.h",
    "u8g2_setup.c", "u8g2_buffer.c", "u8g2_hvline.c", "u8g2_ll_hvline.c",
    "u8g2_intersection.c", "u8g2_bitmap.c", "u8g2_box.c", "u8g2_line.c",
    "u8g2_circle.c", "u8g2_polygon.c", "u8g2_font.c", "u8g2_kerning.c",
    "u8g2_cleardisplay.c",
    "u8x8_setup.c", "u8x8_display.c", "u8x8_byte.c", "u8x8_cad.c",
    "u8x8_gpio.c", "u8x8_d_ssd1306_128x64_noname.c",
    "u8x8_8x8.c", "u8x8_capture.c", "u8x8_u16toa.c",
]

FONTS = ["u8g2_font_4x6_tf", "u8g2_font_5x7_tf", "u8g2_font_6x10_tf",
         "u8g2_font_7x13B_tf", "u8g2_font_10x20_tf"]

BANNER = """/*
  Trimmed copy for: STM32F103C8T6 + SSD1306 128x64 (I2C) + HAL
  Original u8g2 source: https://github.com/olikraus/u8g2
  Copyright (c) Oliver Kraus. BSD 2-Clause license, see ../LICENSE.
  This file was generated by Tools/trim_u8g2.py - do not edit by hand.
*/
"""


def main():
    os.makedirs(CSRC, exist_ok=True)
    for name in COPY:
        shutil.copyfile(os.path.join(SRC, "csrc", name), os.path.join(CSRC, name))
        dst = os.path.join(CSRC, name)
        data = open(dst, "rb").read()
        if not data.endswith(b"\n"):
            open(dst, "wb").write(data + b"\n")
    shutil.copyfile(os.path.join(SRC, "LICENSE"), os.path.join(DST, "LICENSE"))

    # --- setup functions (only the SSD1306 128x64 noname I2C variants) ---
    total = open(os.path.join(SRC, "csrc", "u8g2_d_setup.c"), encoding="utf-8", errors="replace").read()
    out = [BANNER, '#include "u8g2.h"', ""]
    for suffix in ("_1", "_2", "_f"):
        name = "u8g2_Setup_ssd1306_i2c_128x64_noname" + suffix
        start = total.index("void " + name + "(")
        end = total.index("\n}", start) + 3
        out.append(total[start:end])
        out.append("")
    with open(os.path.join(CSRC, "u8g2_d_setup.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))

    # --- memory buffers ---
    mem = [BANNER, '#include "u8g2.h"', ""]
    for suffix, pages in (("_1", 1), ("_2", 2), ("_f", 8)):
        mem.append("uint8_t *u8g2_m_16_8%s(uint8_t *page_cnt)" % suffix)
        mem.append("{")
        mem.append("  *page_cnt = %d;" % pages)
        mem.append("  static uint8_t buf[%d];" % (128 * pages))
        mem.append("  return buf;")
        mem.append("}")
        mem.append("")
    with open(os.path.join(CSRC, "u8g2_d_memory.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(mem))

    # --- fonts ---
    fonts = open(os.path.join(SRC, "csrc", "u8g2_fonts.c"), encoding="utf-8", errors="replace").read()
    starts = {}
    for m in re.finditer(r"const uint8_t (u8g2_font_[A-Za-z0-9_]+)\s*\[", fonts):
        starts.setdefault(m.group(1), m.start())
    order = sorted(starts.items(), key=lambda kv: kv[1])
    chunks = {}
    for i, (name, pos) in enumerate(order):
        end = order[i + 1][1] if i + 1 < len(order) else len(fonts)
        seg = fonts[pos:end]
        last = seg.rfind(";")
        if last > 0:
            seg = seg[:last + 1]
        chunks[name] = seg.strip() + "\n"
    out = [BANNER, '#include "u8g2.h"', ""]
    missing = []
    for name in FONTS:
        if name not in chunks:
            missing.append(name)
            continue
        out.append("/* %s */" % name)
        out.append(chunks[name])
    if missing:
        raise SystemExit("font not found: %s" % ", ".join(missing))
    with open(os.path.join(CSRC, "u8g2_fonts.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))

    print("copied %d files, %d fonts" % (len(COPY), len(FONTS)))
    for name in FONTS:
        print("  %-26s %6d bytes" % (name, len(chunks[name])))


if __name__ == "__main__":
    main()

